"""Parameter profiles: named sets of controller settings that can be saved and loaded.

A profile covers the variables of the polled ``parameters`` block. Values are validated
with the same rules as ``solarlife write``, so a profile can never contain protected
registers. This module has no BLE or daemon dependency.
"""

from __future__ import annotations

import sys
from collections.abc import Iterable, Mapping
from dataclasses import dataclass, field
from datetime import datetime
from importlib import resources
from pathlib import Path
from typing import Any

import yaml

from solarlife import __version__
from solarlife.errors import ProfileError
from solarlife.registers import PARAMETERS, WRITABLE, allowed_values, build_write, block_for

# The variables a profile may contain, in register order.
PARAMETER_NAMES: tuple[str, ...] = tuple(
    v.name for v in sorted(WRITABLE.values(), key=lambda v: v.address) if block_for(v) is PARAMETERS
)

# What the settings do, in the protocol's own terms. Ranges the device accepts are not
# known from the protocol, so none are listed here.
DESCRIPTIONS: dict[str, str] = {
    "battery_type": "Battery chemistry the charging algorithm is set up for.",
    "low_voltage_protection_voltage": "Battery voltage at which the low-voltage protection triggers.",
    "low_voltage_recovery_voltage": "Battery voltage at which the controller recovers from the low-voltage protection.",
    "boost_voltage": "Boost (strong) charging voltage. Lead-acid battery types.",
    "equalizing_voltage": "Equalizing charge voltage. Lead-acid battery types.",
    "float_voltage": "Float charge voltage. Lead-acid battery types.",
    "system_rated_voltage_level": "Rated system voltage; Auto lets the controller detect it.",
    "charge_target_voltage_for_lithium": "Charge target voltage. Lithium battery type only.",
    "charge_recovery_voltage_for_lithium": "Voltage at which charging resumes after the target was reached. Lithium battery type only.",
    "charging_at_zero_celsius": "How the controller charges at or below 0 °C.",
    "mt_series_load_mode": "Load output mode. MT series controllers only.",
    "mt_series_manual_control_default": "Load output state at power-up in manual mode. MT series controllers only.",
}

MARKER_BEGIN = "<!-- parameters:begin (generated by `python -m solarlife.profiles --write docs/parameters.md`) -->"
MARKER_END = "<!-- parameters:end -->"
FLOAT_TOLERANCE = 0.005  # the device stores hundredths of a volt


@dataclass(frozen=True)
class Profile:
    name: str
    values: dict[str, Any]
    description: str = ""
    source: str = ""  # file path or "premade", for messages


@dataclass(frozen=True)
class Change:
    name: str
    unit: str
    old: Any
    new: Any


# -- reading and writing profiles ---------------------------------------------------


def _normalise(name: str, value: Any) -> Any:
    """YAML turns On/Off into booleans; undo that."""
    if isinstance(value, bool):
        return "On" if value else "Off"
    return value


def validate_values(values: Mapping[str, Any]) -> dict[str, Any]:
    """Check names and values; return the values in the form the device takes."""
    if not isinstance(values, Mapping) or not values:
        raise ProfileError("a profile needs a non-empty 'values' mapping")
    unknown = [n for n in values if n not in PARAMETER_NAMES]
    if unknown:
        raise ProfileError(f"not a profile parameter: {', '.join(map(str, unknown))} (see `solarlife variables --writable --block parameters`)")
    results = build_write({n: _normalise(n, v) for n, v in values.items()})
    return {r.name: r.value for r in results}


def parse_profile(text: str, *, default_name: str = "profile", source: str = "") -> Profile:
    try:
        data = yaml.safe_load(text)
    except yaml.YAMLError as exc:
        raise ProfileError(f"{source or 'profile'}: invalid YAML: {exc}") from None
    if not isinstance(data, dict):
        raise ProfileError(f"{source or 'profile'}: expected a mapping with 'values'")
    extra = set(data) - {"name", "description", "values"}
    if extra:
        raise ProfileError(f"{source or 'profile'}: unknown key(s): {', '.join(sorted(map(str, extra)))}")
    try:
        values = validate_values(data.get("values"))
    except ProfileError as exc:
        raise ProfileError(f"{source or 'profile'}: {exc}") from None
    except Exception as exc:  # InvalidWriteError: name the profile
        raise type(exc)(f"{source or 'profile'}: {exc}") from None
    return Profile(str(data.get("name") or default_name), values, str(data.get("description") or ""), source)


def _premade_dir():
    return resources.files("solarlife") / "premade"


def list_premade() -> list[Profile]:
    profiles = []
    for entry in sorted(_premade_dir().iterdir(), key=lambda e: e.name):
        if entry.name.endswith(".yml"):
            profiles.append(parse_profile(entry.read_text(encoding="utf-8"), default_name=entry.name[:-4], source="premade"))
    return profiles


def is_path(ref: str) -> bool:
    return "/" in ref or ref.endswith((".yml", ".yaml"))


def load_profile(ref: str) -> Profile:
    """A premade profile by name, or a file if the reference looks like a path."""
    if is_path(ref):
        path = Path(ref)
        try:
            text = path.read_text(encoding="utf-8")
        except OSError as exc:
            raise ProfileError(f"cannot read profile {ref}: {exc.strerror or exc}") from None
        return parse_profile(text, default_name=path.stem, source=str(path))
    for profile in list_premade():
        if profile.name == ref:
            return profile
    names = ", ".join(p.name for p in list_premade())
    raise ProfileError(f"no premade profile {ref!r} (available: {names}); use ./{ref}.yml for a file")


def profile_from_values(values: Iterable[Mapping[str, Any]], *, name: str, description: str = "") -> Profile:
    """Build a profile from the values of a ``read parameters`` result."""
    by_name = {v["name"]: v["value"] for v in values}
    picked = {n: (round(by_name[n], 2) if isinstance(by_name[n], float) else by_name[n]) for n in PARAMETER_NAMES if n in by_name}
    if not picked:
        raise ProfileError("the device returned none of the profile parameters")
    return Profile(name, picked, description)


def dump_profile(profile: Profile, *, device: str | None = None, when: datetime | None = None) -> str:
    when = when or datetime.now().astimezone()
    header = [f"# solarlife profile, saved {when.isoformat(timespec='seconds')} by solarlife {__version__}"]
    if device:
        header.append(f"# from device {device}")
    body = {"name": profile.name}
    if profile.description:
        body["description"] = profile.description
    body["values"] = dict(profile.values)
    return "\n".join(header) + "\n" + yaml.safe_dump(body, sort_keys=False, allow_unicode=True)


# -- comparing -----------------------------------------------------------------------


def same(a: Any, b: Any) -> bool:
    if isinstance(a, (int, float)) and isinstance(b, (int, float)) and not isinstance(a, bool) and not isinstance(b, bool):
        return abs(a - b) < FLOAT_TOLERANCE
    return str(a).strip().casefold() == str(b).strip().casefold()


def diff(profile: Profile, current: Iterable[Mapping[str, Any]]) -> list[Change]:
    """What loading the profile would change, in register order."""
    now = {v["name"]: v for v in current}
    changes = []
    for name in PARAMETER_NAMES:
        if name not in profile.values:
            continue
        have = now.get(name)
        old = None if have is None else have["value"]
        if have is None or not same(old, profile.values[name]):
            changes.append(Change(name, WRITABLE[name].unit, old, profile.values[name]))
    return changes


# -- documentation -------------------------------------------------------------------


def parameters_table() -> str:
    lines = ["| Name | Address | Unit | Accepted values | Description |", "| --- | --- | --- | --- | --- |"]
    for name in PARAMETER_NAMES:
        v = WRITABLE[name]
        allowed = allowed_values(name)
        accepted = ", ".join(f"`{a}`" for a in allowed) if allowed else f"number ({v.unit}), steps of {1 / v.multiplier:g}" if v.multiplier else "integer"
        lines.append(f"| `{name}` | 0x{v.address:04x} | {v.unit or '-'} | {accepted} | {DESCRIPTIONS.get(name, '')} |")
    return "\n".join(lines)


def render_doc(text: str) -> str:
    """Replace the generated block of docs/parameters.md."""
    start, end = text.find(MARKER_BEGIN), text.find(MARKER_END)
    if start < 0 or end < start:
        raise ProfileError("parameter table markers not found")
    return text[: start + len(MARKER_BEGIN)] + "\n\n" + parameters_table() + "\n\n" + text[end:]


def main(argv: list[str] | None = None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    if argv[:1] == ["--write"] and len(argv) == 2:
        path = Path(argv[1])
        path.write_text(render_doc(path.read_text(encoding="utf-8")), encoding="utf-8")
        return 0
    if not argv:
        print(parameters_table())
        return 0
    print("usage: python -m solarlife.profiles [--write FILE]", file=sys.stderr)
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
